    """Retrieve a specific annotated image resource."""
    if resource_id in resources:
        return {
            "contents": [
                {
                    "uri": f"image://{resource_id}",
                    "mimeType": "image/png",
                    "text": resources[resource_id]
                }
            ]
        }
    raise HTTPException(status_code=404, detail="Resource not found")

