# --------------------------------------------------------------
# Helper: run Moondream on an image + optional question
# --------------------------------------------------------------
def run_moondream(image_bytes: bytes, question: str | None) -> str:
    """Return a description or answer generated by Moondream."""
    pil_img = Image.open(io.BytesIO(image_bytes)).convert("RGB")
    prompt = question if question else "Describe this image."
    inputs = processor(pil_img, prompt, return_tensors="pt").to(model.device)

    generated_ids = model.generate(**inputs, max_new_tokens=256, do_sample=False)
    output_text = processor.decode(generated_ids[0], skip_special_tokens=True)
    answer = output_text.replace(prompt, "").strip()
    return answer

# --------------------------------------------------------------
# Helper: detect objects using OwlViT
# --------------------------------------------------------------
def detect_objects(image_bytes: bytes, text_queries: List[str]) -> Tuple[List[dict], Image.Image]:
    """Detect objects in image and return bounding boxes with annotated image."""
    pil_img = Image.open(io.BytesIO(image_bytes)).convert("RGB")
    
    # Process image and text queries
    inputs = detection_processor(text=text_queries, images=pil_img, return_tensors="pt")
    
    # Run detection
    with torch.no_grad():
        outputs = detection_model(**inputs)
    
    # Process results
    target_sizes = torch.Tensor([pil_img.size[::-1]])
    results = detection_processor.post_process_object_detection(outputs=outputs, target_sizes=target_sizes, threshold=0.1)
    
    boxes = results[0]["boxes"]
    scores = results[0]["scores"]
    labels = results[0]["labels"]
    
    # Create annotated image
    draw = ImageDraw.Draw(pil_img)
    
    # Try to load a font, fallback to default if not available
    try:
        font = ImageFont.truetype("/System/Library/Fonts/Arial.ttf", 20)
    except:
        font = ImageFont.load_default()
    
    detections = []
    colors = ['red', 'blue', 'green', 'yellow', 'purple', 'orange', 'pink', 'cyan']
    
    for i, (box, score, label) in enumerate(zip(boxes, scores, labels)):
        if score > 0.1:  # Confidence threshold
            x1, y1, x2, y2 = box.tolist()
            query_text = text_queries[label]
            color = colors[i % len(colors)]
            
            # Draw bounding box
            draw.rectangle([x1, y1, x2, y2], outline=color, width=3)
            
            # Draw label
            label_text = f"{query_text}: {score:.2f}"
            draw.text((x1, y1-25), label_text, fill=color, font=font)
            
            detections.append({
                "query": query_text,
                "confidence": float(score),
                "bbox": [float(x1), float(y1), float(x2), float(y2)],
                "position": f"center at ({int((x1+x2)/2)}, {int((y1+y2)/2)})"
            })
    
    return detections, pil_img

# --------------------------------------------------------------
# Helper: convert PIL image to base64
# --------------------------------------------------------------
def pil_to_base64(pil_img: Image.Image) -> str:
    """Convert PIL image to base64 string."""
    buffer = io.BytesIO()
    pil_img.save(buffer, format="PNG")
    return base64.b64encode(buffer.getvalue()).decode('utf-8')

