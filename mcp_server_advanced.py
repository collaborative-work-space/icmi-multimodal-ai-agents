@app.post("/tools/call")
async def call_tool(request: Request):
    """Call a specific tool."""
    try:
        body = await request.json()
        tool_name = body.get("name")
        arguments = body.get("arguments", {})
        
        if tool_name == "find_item_in_image":
            image_base64 = arguments.get("image_base64", "")
            item_description = arguments.get("item_description", "")
            
            # Decode base64 image
            image_bytes = base64.b64decode(image_base64)
            
            # Use Moondream to find and describe the item
            question = f"Find and describe the {item_description} in this image. Where is it located?"
            answer = run_moondream(image_bytes, question)
            
            # Also try object detection for more precise location
            detections, annotated_img = detect_objects(image_bytes, [item_description])
            
            result = {
                "answer": answer,
                "item_description": item_description,
                "detections": detections,
                "annotated_image_base64": pil_to_base64(annotated_img),
                "success": True
            }
            
            return {"result": result}
            
        elif tool_name == "describe_image":
            image_base64 = arguments.get("image_base64", "")
            question = arguments.get("question", "Describe this image.")
            
            # Decode base64 image
            image_bytes = base64.b64decode(image_base64)
            
            # Run Moondream analysis
            answer = run_moondream(image_bytes, question)
            
            return {
                "result": {
                    "answer": answer,
                    "question": question,
                    "success": True
                }
            }
            
        elif tool_name == "annotate_object":
            image_base64 = arguments.get("image_base64", "")
            object_queries = arguments.get("object_queries", [])
            
            # Decode base64 image
            image_bytes = base64.b64decode(image_base64)
            
            # Detect objects and create annotated image
            detections, annotated_img = detect_objects(image_bytes, object_queries)
            
            return {
                "result": {
                    "detections": detections,
                    "annotated_image_base64": pil_to_base64(annotated_img),
                    "object_queries": object_queries,
                    "success": True
                }
            }
            
        elif tool_name == "annotate_object_resource":
            image_base64 = arguments.get("image_base64", "")
            object_queries = arguments.get("object_queries", [])
            
            # Decode base64 image
            image_bytes = base64.b64decode(image_base64)
            
            # Detect objects and create annotated image
            detections, annotated_img = detect_objects(image_bytes, object_queries)
            
            # Store as resource
            resource_id = str(uuid.uuid4())
            annotated_base64 = pil_to_base64(annotated_img)
            resources[resource_id] = annotated_base64
            
            return {
                "result": {
                    "detections": detections,
                    "resource_id": resource_id,
                    "resource_uri": f"image://{resource_id}",
                    "success": True
                }
            }
            
        elif tool_name == "get_model_info":
            return {
                "result": {
                    "vision_model": MODEL_NAME,
                    "detection_model": DETECTION_MODEL_NAME,
                    "capabilities": [
                        "image description",
                        "visual question answering", 
                        "object detection",
                        "image annotation",
                        "MCP resource sharing"
                    ],
                    "success": True
                }
            }
        else:
            raise HTTPException(status_code=400, detail=f"Unknown tool: {tool_name}")
            
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Tool call failed: {e}")

